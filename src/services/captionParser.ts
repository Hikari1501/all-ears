import { CaptionCue } from '../types';

/**
 * Converts seconds into MM:SS format (or HH:MM:SS if > 1 hour)
 */
export function formatTime(seconds: number): string {
  if (isNaN(seconds) || seconds < 0) return '00:00';
  const totalSecs = Math.floor(seconds);
  const hrs = Math.floor(totalSecs / 3600);
  const mins = Math.floor((totalSecs % 3600) / 60);
  const secs = totalSecs % 60;

  if (hrs > 0) {
    return `${hrs.toString().padStart(2, '0')}:${mins.toString().padStart(2, '0')}:${secs.toString().padStart(2, '0')}`;
  }
  return `${mins.toString().padStart(2, '0')}:${secs.toString().padStart(2, '0')}`;
}

/**
 * Converts MM:SS or HH:MM:SS or timestamp string to seconds
 */
export function parseTimeToSeconds(timeStr: string): number {
  const clean = timeStr.trim().replace(',', '.');
  const parts = clean.split(':').map(Number);
  if (parts.some(isNaN)) return 0;

  if (parts.length === 3) {
    return parts[0] * 3600 + parts[1] * 60 + parts[2];
  }
  if (parts.length === 2) {
    return parts[0] * 60 + parts[1];
  }
  return Number(timeStr) || 0;
}

/**
 * Parses WebVTT or SubRip (.srt) caption content into structured CaptionCue items
 */
export function parseCaptions(content: string): CaptionCue[] {
  const cues: CaptionCue[] = [];
  const normalized = content.replace(/\r\n/g, '\n').replace(/\r/g, '\n');
  const blocks = normalized.split(/\n\s*\n/);

  for (let i = 0; i < blocks.length; i++) {
    const block = blocks[i].trim();
    if (!block || block.startsWith('WEBVTT') || block.startsWith('NOTE')) {
      continue;
    }

    const lines = block.split('\n');
    let timeLineIdx = lines.findIndex(l => l.includes('-->'));

    if (timeLineIdx !== -1) {
      const timeLine = lines[timeLineIdx];
      const match = timeLine.match(/((?:\d{2}:)?\d{2}:\d{2}[.,]\d{3})\s*-->\s*((?:\d{2}:)?\d{2}:\d{2}[.,]\d{3})/);

      if (match) {
        const startSec = parseTimeToSeconds(match[1]);
        const endSec = parseTimeToSeconds(match[2]);
        const text = lines.slice(timeLineIdx + 1).join(' ').trim();

        if (text) {
          cues.push({
            id: `cue-${cues.length + 1}-${Date.now().toString(36)}`,
            start: Math.round(startSec * 100) / 100,
            end: Math.round(endSec * 100) / 100,
            text: text.replace(/<[^>]+>/g, '') // remove HTML tags if present
          });
        }
      }
    }
  }

  return cues.sort((a, b) => a.start - b.start);
}

/**
 * Exports CaptionCue array back to WebVTT string
 */
export function exportToWebVTT(cues: CaptionCue[]): string {
  let vtt = 'WEBVTT - Generated by All Ears\n\n';
  cues.forEach((cue, index) => {
    const startStr = formatVttTime(cue.start);
    const endStr = formatVttTime(cue.end);
    vtt += `${index + 1}\n${startStr} --> ${endStr}\n${cue.text}\n\n`;
  });
  return vtt;
}

function formatVttTime(seconds: number): string {
  const hrs = Math.floor(seconds / 3600);
  const mins = Math.floor((seconds % 3600) / 60);
  const secs = (seconds % 60).toFixed(3);
  return `${hrs.toString().padStart(2, '0')}:${mins.toString().padStart(2, '0')}:${secs.padStart(6, '0')}`;
}

/**
 * Parses YouTube video ID from various YouTube URL formats
 */
export function extractYouTubeId(url: string): string | null {
  if (!url) return null;
  const match = url.match(/(?:youtu\.be\/|youtube\.com\/(?:embed\/|v\/|watch\?v=|watch\?.+&v=))([\w-]{11})/);
  return match ? match[1] : null;
}
